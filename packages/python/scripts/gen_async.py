"""Generate src/toolguard/_async_client.py from src/toolguard/_client.py.

Run from packages/python:  python scripts/gen_async.py
Pass --check to fail if the generated file is out of date (used in tests).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "toolguard" / "_client.py"
DST = ROOT / "src" / "toolguard" / "_async_client.py"

HEADER = '"""Asynchronous ToolGuard client.\n\nGENERATED by scripts/gen_async.py from _client.py. Do not edit by hand.\n"""\n'

REPLACEMENTS = [
    (r'^""".*?"""\n', HEADER, re.S),
    (r"^import time\n", "import asyncio\n", re.M),
    (r"\bclass ToolGuard\b", "class AsyncToolGuard", 0),
    (r'"ToolGuard"', '"AsyncToolGuard"', 0),
    (r"httpx\.Client\b", "httpx.AsyncClient", 0),
    (r"self\._http\.close\(\)", "await self._http.aclose()", 0),
    (r"def __enter__", "async def __aenter__", 0),
    (r"def __exit__", "async def __aexit__", 0),
    (r"(\n    )def (?!__init__)(\w+)\((\s*)self", r"\1async def \2(\3self", 0),
    (r"self\.close\(\)", "await self.close()", 0),
    (r"self\._request\(", "await self._request(", 0),
    (r"(?<!await )self\.(get_approval|authorize|resolve_approval)\(", r"await self.\1(", 0),
    (r"time\.sleep\(", "await asyncio.sleep(", 0),
    (r"self\._http\.request\(", "await self._http.request(", 0),
    (r"Client for the ToolGuard API\.", "Async client for the ToolGuard API. Same methods as ToolGuard, awaited.", 0),
]


def generate() -> str:
    text = SRC.read_text()
    for pattern, repl, flags in REPLACEMENTS:
        text = re.sub(pattern, repl, text, flags=flags)
    # A call that came back from a function in a dict lookup needs parentheses.
    text = re.sub(r"await self\._request\(([^\n]*?)\)\[\"items\"\]", r'(await self._request(\1))["items"]', text)
    # The deadline still uses time.monotonic, imported under a private name.
    text = text.replace("deadline = time.monotonic()", "deadline = _monotonic()")
    text = text.replace("remaining = deadline - time.monotonic()", "remaining = deadline - _monotonic()")
    text = text.replace("import uuid\n", "import uuid\nfrom time import monotonic as _monotonic\n", 1)
    return text


def main() -> int:
    generated = generate()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != generated:
            print("_async_client.py is out of date. Run: python scripts/gen_async.py", file=sys.stderr)
            return 1
        return 0
    DST.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
